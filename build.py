"""Build two static pages using the AcademicPages theme and existing profile data."""

import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
data = json.loads((ROOT / "content.json").read_text())
esc = html.escape


def link(url, label, extra=""):
    return f'<a href="{esc(url, quote=True)}"{extra}>{label}</a>'


def icon(name):
    paths = {
        "email": '<rect x="3" y="5" width="18" height="14" rx="2"/><path d="m3 6 9 7 9-7"/>',
        "scholar": '<path d="m2 8 10-5 10 5-10 5-10-5Zm4 3v6c4 3 8 3 12 0v-6M22 8v8"/>',
        "github": '<path d="M9 19c-4 1-4-2-6-2m12 4v-4c0-1 .2-1.7-.6-2.4 3-.3 6-1.5 6-6A5 5 0 0 0 19 5c.2-1 .2-2-1-3-2 0-4 1-4 1a14 14 0 0 0-4 0S8 2 6 2c-1 1-1 2-1 3a5 5 0 0 0-1.5 3.6c0 4.5 3 5.7 6 6-.7.7-.6 1.4-.6 2.4v4"/>',
    }
    return (
        '<svg class="contact-icon" viewBox="0 0 24 24" fill="none" '
        'stroke="currentColor" stroke-width="1.6" stroke-linecap="round" '
        f'stroke-linejoin="round" aria-hidden="true">{paths[name]}</svg>'
    )


def sidebar(base):
    degrees = []
    for degree in data["education"]:
        advisor = ""
        if degree.get("advisor"):
            advisor = (
                '<span class="education-advisor">Advisor: '
                + link(degree["advisor_url"], esc(degree["advisor"]))
                + "</span>"
            )
        degrees.append(
            '<div class="education-item">'
            f'<dt>{esc(degree["degree"])}</dt>'
            f'<dd>{esc(degree["school"])}<span class="education-year">{degree["year"]}</span>'
            f"{advisor}</dd></div>"
        )
    contacts = [
        (data["scholar"], "Google Scholar", "scholar"),
        (data["github"], "GitHub", "github"),
        ("mailto:" + data["email"], "Email", "email"),
    ]
    contact_links = "".join(
        f'<li>{link(url, icon(kind) + esc(label))}</li>'
        for url, label, kind in contacts
    )
    return f"""
    <aside class="sidebar profile" aria-label="Profile and education">
      <a class="author__avatar" href="{base}" aria-label="Yanru Xiao homepage">
        <img src="{base}assets/portrait.jpg" width="175" height="200"
             alt="{esc(data["name"])}" fetchpriority="high">
      </a>
      <div class="author__content">
        <h2 class="author__name">{esc(data["name"])}</h2>
        <p class="author__bio"><strong>{esc(data["position"])}</strong><br>
          {esc(data["affiliation"])}</p>
      </div>
      <ul class="author__urls profile-links">{contact_links}</ul>
      <section class="profile-education" aria-labelledby="education-heading">
        <h2 id="education-heading">Education</h2>
        <dl>{"".join(degrees)}</dl>
      </section>
    </aside>"""


papers = {
    paper["title"]: paper
    for group in data["publication_groups"]
    for paper in group["papers"]
}


def render_paper(paper):
    authors = ", ".join(
        f'<strong>{esc(author)}</strong>'
        if author == data["name"]
        else esc(author)
        for author in paper["authors"]
    )
    actions = " ".join(
        link(paper[key], label, ' class="paper-link"')
        for key, label in [("paper", "Paper"), ("pdf", "PDF"), ("code", "Code")]
        if key in paper
    )
    title_url = paper.get("paper") or paper["pdf"]
    return f"""
      <li class="publication">
        <h3>{link(title_url, esc(paper["title"]))}</h3>
        <p class="paper-authors">{authors}</p>
        <p class="paper-venue">{esc(paper["venue"])}
          <span class="paper-year">({paper["year"]})</span></p>
        <div class="paper-links">{actions}</div>
      </li>"""


def page_document(title, content, page="about"):
    base = "./" if page == "about" else "../"
    about_attr = ' aria-current="page"' if page == "about" else ""
    pubs_attr = ' aria-current="page"' if page == "publications" else ""
    schema = {
        "@context": "https://schema.org",
        "@type": "Person",
        "name": data["name"],
        "jobTitle": data["position"],
        "worksFor": {"@type": "Organization", "name": data["affiliation"]},
        "sameAs": [data["scholar"], data["github"]],
        "alumniOf": [
            {"@type": "CollegeOrUniversity", "name": degree["school"]}
            for degree in data["education"]
        ],
    }
    return f"""<!doctype html>
<!-- AcademicPages theme, MIT license; static layout generated by build.py. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="description" content="{esc(data["description"], quote=True)}">
  <meta name="theme-color" content="#ffffff">
  <meta property="og:title" content="{esc(data["name"])} | {esc(title)}">
  <meta property="og:description" content="{esc(data["description"], quote=True)}">
  <meta property="og:type" content="website">
  <title>{esc(title)} · {esc(data["name"])}</title>
  <link rel="icon" href="{base}assets/favicon.svg" type="image/svg+xml">
  <link rel="stylesheet" href="{base}assets/academicpages.css">
  <link rel="stylesheet" href="{base}assets/site.css">
  <script type="application/ld+json">{json.dumps(schema)}</script>
</head>
<body>
  <a class="skip-link" href="#content">Skip to content</a>
  <header class="masthead">
    <div class="masthead__inner-wrap">
      <nav class="site-nav" aria-label="Main navigation">
        <a class="site-name" href="{base}">{esc(data["name"])}</a>
        <div class="nav-links">
          <a href="{base}"{about_attr}>About</a>
          <a href="{base}publications/"{pubs_attr}>Publications</a>
          <a href="{base}#service">Service</a>
        </div>
      </nav>
    </div>
  </header>
  <div id="main">
    {sidebar(base)}
    <main id="content" class="page">
      <h1 class="page__title">{esc(title)}</h1>
      <div class="page__content">{content}</div>
    </main>
  </div>
  <footer class="site-footer">
    <div><span>© 2026 {esc(data["name"])}</span>
      <span>Built with the {link("https://github.com/academicpages/academicpages.github.io", "AcademicPages")} theme</span></div>
  </footer>
</body>
</html>
"""


bio = "".join(f"<p>{esc(text)}</p>" for text in data["bio"])
bio = bio.replace(
    "advised by Cong Wang",
    "advised by " + link(data["advisor_url"], "Cong Wang"),
)
featured = "".join(render_paper(papers[title]) for title in data["featured_titles"])
about_content = f"""
        <div class="bio">{bio}</div>
        <section id="selected-publications" aria-labelledby="selected-heading">
          <div class="section-heading">
            <h2 id="selected-heading">Selected publications</h2>
            {link("./publications/", 'All publications <span aria-hidden="true">→</span>', ' class="section-link"')}
          </div>
          <ul class="publications">{featured}</ul>
        </section>
        <section id="service" aria-labelledby="service-heading">
          <h2 id="service-heading">Academic service</h2>
          <p class="service-intro">Reviewer for the following conferences and journals.</p>
          <dl class="service-list">
            <div><dt>Conferences</dt><dd>{esc(" · ".join(data["services"]["conferences"]))}</dd></div>
            <div><dt>Journals</dt><dd>{esc(" · ".join(data["services"]["journals"]))}</dd></div>
          </dl>
        </section>"""

groups = []
for group in data["publication_groups"]:
    groups.append(
        '<section class="publication-group">'
        f'<h2>{esc(group["title"])}</h2>'
        f'<ul class="publications">{"".join(render_paper(paper) for paper in group["papers"])}</ul>'
        "</section>"
    )
pubs_content = (
    '<p class="publication-intro">'
    + link(data["scholar"], 'Google Scholar <span aria-hidden="true">↗</span>')
    + '</p>'
    + "".join(groups)
)

(ROOT / "index.html").write_text(page_document("About me", about_content))
(ROOT / "publications").mkdir(exist_ok=True)
(ROOT / "publications/index.html").write_text(
    page_document("Publications", pubs_content, "publications")
)
print(f"Built 2 pages; 3 homepage selections and {len(papers)} full publications.")
